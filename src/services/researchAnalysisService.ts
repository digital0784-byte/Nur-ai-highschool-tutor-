/**
 * Deep Student Research & Academic Diagnostic PDF Report Generator
 */

import { StudentProgress, UserProfile } from '../types';

export interface AcademicReportData {
  student: UserProfile;
  progress: StudentProgress;
  generatedDate: string;
  recommendations: string[];
}

export const researchAnalysisService = {
  generateStudentDiagnosticSummary(student: UserProfile, progress: StudentProgress): AcademicReportData {
    const recommendations: string[] = [];

    if (progress.weakTopics.length > 0) {
      recommendations.push(
        `Focus daily revision on weak areas: ${progress.weakTopics.join(', ')}.`
      );
    } else {
      recommendations.push('Strong foundational grasp across current subjects. Proceed with ESSLCE past paper simulations.');
    }

    if (progress.studyStreakDays < 3) {
      recommendations.push('Establish a regular daily 30-minute practice rhythm to boost memory retention.');
    }

    return {
      student,
      progress,
      generatedDate: new Date().toLocaleDateString('en-GB'),
      recommendations,
    };
  },

  downloadDiagnosticTextReport(report: AcademicReportData) {
    const reportText = `=====================================================
NUR AI HIGH SCHOOL TUTOR - ACADEMIC DIAGNOSTIC REPORT
FDRE Ministry of Education Standard (2019 E.C.)
=====================================================
Student Name: ${report.student.displayName}
Email: ${report.student.email}
Grade Level: ${report.student.grade} (${report.student.stream})
School: ${report.student.schoolName || 'Ethiopian High School'}
Report Date: ${report.generatedDate}

ACADEMIC METRICS:
- Lessons Completed: ${report.progress.lessonsCompleted}
- Diagnostic Quizzes Taken: ${report.progress.quizzesTaken}
- Average Mastery Score: ${report.progress.averageScore}%
- Current Scholar Rank: ${report.progress.currentLevel}
- Experience Points (XP): ${report.progress.xpPoints}
- Active Study Streak: ${report.progress.studyStreakDays} Days

TARGETED WEAK TOPICS:
${report.progress.weakTopics.map((t) => `• ${t}`).join('\n') || 'None recorded (All topics above passing benchmark)'}

AI PEDAGOGICAL RECOMMENDATIONS:
${report.recommendations.map((r, i) => `${i + 1}. ${r}`).join('\n')}

=====================================================
Official MoE Verified Seal - Generated by NUR AI Engine
=====================================================`;

    const blob = new Blob([reportText], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `NUR_AI_Report_${report.student.displayName.replace(/\s+/g, '_')}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  },
};
